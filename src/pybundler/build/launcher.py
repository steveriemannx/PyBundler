"""Compiling (or scripting) the native launcher and precompiling bytecode."""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

from ..errors import ToolchainError
from ..fsutil import ensure_dir, make_executable, write_text
from ..interp import sanitized_env
from ..log import Logger
from ..targets import Target

RESOURCE_DIR = Path(__file__).resolve().parent.parent / "resources"
LAUNCHER_C = RESOURCE_DIR / "launcher.c"
BOOT_PY = RESOURCE_DIR / "boot.py"
DEFAULT_ICON = RESOURCE_DIR / "default.ico"

_MSVC_NAMES = {"cl", "cl.exe", "clang-cl", "clang-cl.exe"}


@dataclass(frozen=True)
class LauncherConfig:
    name: str
    build_id: str
    onefile: bool
    home_rel: str
    exe_rel: str
    site_rel: str
    lib_rel: str
    windowed: bool
    console: bool
    compress: bool
    icon: Path | None = None


@dataclass(frozen=True)
class CompileInvocation:
    command: list[str]
    cwd: Path
    header: Path
    output: Path
    object_file: Path | None
    resource_command: list[str] | None = None
    resource_script: Path | None = None
    resource_output: Path | None = None


def compiler_family(compiler: str) -> str:
    """Return ``msvc`` for cl/clang-cl, ``gcc`` for cc/clang/gcc."""
    name = Path(compiler.replace("\\", "/")).name.lower()
    return "msvc" if name in _MSVC_NAMES else "gcc"


def _find_resource_compiler(compiler: str) -> str | None:
    """Locate ``rc.exe`` (the Windows resource compiler) for the MSVC toolchain."""
    sibling = Path(compiler.replace("\\", "/")).parent / "rc.exe"
    if sibling.is_file():
        return str(sibling)
    return shutil.which("rc")


def find_compiler() -> str | None:
    """Find a supported host compiler.

    Windows uses the Microsoft toolchain (``cl`` or ``clang-cl``) only; MinGW is
    deliberately not selected.  POSIX platforms use the system C compiler.
    """
    override = os.environ.get("CC")
    if sys.platform == "win32":
        candidates = [override] if override and compiler_family(override) == "msvc" else []
        candidates.extend(["cl", "clang-cl"])
    else:
        candidates = [override, "cc", "clang", "gcc"]
    for candidate in candidates:
        if not candidate:
            continue
        resolved = shutil.which(candidate)
        if resolved:
            return resolved
    return None


@lru_cache(maxsize=16)
def _zlib_probe(compiler: str, bits: int) -> bool:
    family = compiler_family(compiler)
    with tempfile.TemporaryDirectory(prefix="pybundler-zlib-") as directory:
        source = Path(directory) / "probe.c"
        output = Path(directory) / "probe.exe" if family == "msvc" else Path(directory) / "probe"
        source.write_text(
            "#include <zlib.h>\n"
            "int main(void) { return zlibVersion() == 0; }\n",
            encoding="utf-8",
        )
        try:
            if family == "msvc":
                command = [compiler, "/nologo", source.name, f"/Fe{output.name}", "zlib.lib", "/link"]
            else:
                command = [compiler, source.name, "-o", output.name, "-lz"]
                if bits == 32:
                    command.insert(1, "-m32")
            proc = subprocess.run(
                command, capture_output=True, text=True, encoding="utf-8", errors="replace", cwd=directory
            )
        except OSError:
            return False
        return proc.returncode == 0


def zlib_available(compiler: str | None = None, *, bits: int = 64) -> bool:
    compiler = compiler or find_compiler()
    if compiler is None:
        return False
    return _zlib_probe(compiler, bits)


def _config_header(config: LauncherConfig, *, compress: bool | None = None) -> str:
    if compress is None:
        compress = config.compress
    values: dict[str, str | int] = {
        "PYB_NAME": config.name,
        "PYB_BUILD_ID": config.build_id,
        "PYB_MODE_ONEFILE": 1 if config.onefile else 0,
        "PYB_HOME_REL": config.home_rel,
        "PYB_EXE_REL": config.exe_rel,
        "PYB_SITE_REL": config.site_rel,
        "PYB_LIB_REL": config.lib_rel,
        "PYB_USE_ZLIB": 1 if compress else 0,
        "PYB_WINDOWED": 1 if config.windowed else 0,
        "PYB_CONSOLE": 1 if config.console else 0,
    }
    lines = ["/* generated by PyBundler -- do not edit */"]
    for key, value in values.items():
        literal = json.dumps(value) if isinstance(value, str) else str(value)
        lines.append(f"#define {key} {literal}")
    return "\n".join(lines) + "\n"


def build_compile_invocation(
    config: LauncherConfig,
    output: Path,
    compiler: str,
    *,
    compress: bool,
    target: Target | None = None,
) -> CompileInvocation:
    """Build the compiler command line without running it (unit-testable)."""
    family = compiler_family(compiler)
    cwd = ensure_dir(output.parent)
    header = cwd / "pybundler_launcher_config.h"
    object_file = cwd / "pybundler_launcher.obj" if family == "msvc" else None
    resource_command: list[str] | None = None
    resource_script: Path | None = None
    resource_output: Path | None = None
    if family == "msvc":
        command = [
            compiler,
            "/nologo",
            "/O2",
            "/MT",
            "/W3",
            f"/FI{header}",
            f"/Fo{object_file}",
            f"/Fe{output}",
            str(LAUNCHER_C),
            "/link",
        ]
        if config.windowed:
            # GUI-subsystem binary: Windows must not create a console window for
            # the launcher.  A console-subsystem binary flashes one before
            # FreeConsole() runs, which looks like a cmd window blink.
            command.extend(["/SUBSYSTEM:WINDOWS", "/ENTRY:mainCRTStartup"])
        command.extend(["shell32.lib", "user32.lib"])
        if compress:
            command.append("zlib.lib")
        # Embed an application icon.  ``icon`` may point at a Windows .ico from
        # the spec; otherwise the bundled default icon is used.
        icon = config.icon if config.icon is not None else DEFAULT_ICON
        if icon.suffix.lower() != ".ico" or not icon.is_file():
            icon = DEFAULT_ICON
        resource_compiler = _find_resource_compiler(compiler)
        if resource_compiler is not None and icon.is_file():
            resource_script = cwd / "launcher_icon.rc"
            resource_output = cwd / "launcher_icon.res"
            resource_script.write_text(
                f'IDI_APP ICON "{icon.as_posix()}"\n', encoding="utf-8"
            )
            resource_command = [
                resource_compiler,
                "/nologo",
                f"/fo{resource_output}",
                str(resource_script),
            ]
            link_index = command.index("/link")
            command.insert(link_index, str(resource_output))
        else:
            resource_command = None
            resource_script = None
            resource_output = None
    else:
        command = [
            compiler,
            "-O2",
            "-std=c99",
            "-Wall",
            "-Wextra",
            "-D_FILE_OFFSET_BITS=64",
        ]
        if target is not None and target.is_32bit and target.is_posix:
            command.append("-m32")
        command.extend(
            [
                "-include",
            header.name,
                "-o",
                output.name,
                str(LAUNCHER_C),
            ]
        )
        if compress:
            command.append("-lz")
    header.write_text(_config_header(config, compress=compress), encoding="utf-8")
    return CompileInvocation(
        command=command,
        cwd=cwd,
        header=header,
        output=output,
        object_file=object_file,
        resource_command=resource_command if family == "msvc" else None,
        resource_script=resource_script if family == "msvc" else None,
        resource_output=resource_output if family == "msvc" else None,
    )


def compile_launcher(
    config: LauncherConfig,
    output: Path,
    *,
    target: Target,
    compiler: str | None = None,
    logger: Logger | None = None,
) -> None:
    """Compile ``launcher.c`` with the application's constants baked in."""
    compiler = compiler or find_compiler()
    if compiler is None:
        if target.is_windows:
            raise ToolchainError(
                "no Microsoft C compiler found",
                hint=(
                    "install Visual Studio Build Tools with the C++ workload and run "
                    "PyBundler from a Developer Command Prompt (vcvarsall), or install "
                    "LLVM and use clang-cl. MinGW is not used by PyBundler."
                ),
            )
        raise ToolchainError(
            "no C compiler found, which is required for native launchers",
            hint=(
                "install Xcode Command Line Tools (macOS), build-essential (Linux), "
                "base clang (FreeBSD), or pass --launcher script for an onedir build"
            ),
        )
    family = compiler_family(compiler)
    if family == "msvc" and not target.is_windows:
        raise ToolchainError(
            f"{compiler} is an MSVC-style compiler but the target is not Windows",
            hint="use cc/clang/gcc for macOS, Linux and FreeBSD",
        )
    if target.is_windows and family != "msvc":
        raise ToolchainError(
            f"{compiler} is not a Microsoft C compiler",
            hint=(
                "PyBundler builds Windows launchers with cl.exe or clang-cl. "
                "Open a Developer Command Prompt / vcvarsall and retry."
            ),
        )
    if config.compress and not zlib_available(compiler, bits=target.bits):
        raise ToolchainError(
            "zlib headers/library are missing but onefile compression is enabled",
            hint=(
                "install zlib development files, or pass --no-compress. "
                "On Windows zlib is optional; without it onefile payloads are stored."
            ),
        )
    invocation = build_compile_invocation(
        config, output, compiler, compress=config.compress, target=target
    )
    ensure_dir(invocation.cwd)
    if invocation.resource_command is not None:
        try:
            subprocess.run(
                invocation.resource_command,
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                cwd=str(invocation.cwd),
            )
        except OSError:
            # The icon is cosmetic: keep building without it.
            pass
    if invocation.resource_output is not None and not invocation.resource_output.is_file():
        if logger is not None:
            logger.detail("icon resource could not be compiled; building without an icon")
    if logger is not None:
        logger.detail(" ".join(invocation.command))
    try:
        try:
            proc = subprocess.run(
                invocation.command,
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                cwd=str(invocation.cwd),
            )
        except OSError as exc:
            raise ToolchainError(
                f"cannot run the C compiler {compiler}: {exc}",
                hint="check that the compiler is installed and on PATH",
            ) from exc
    finally:
        invocation.header.unlink(missing_ok=True)
        if invocation.object_file is not None:
            invocation.object_file.unlink(missing_ok=True)
        if invocation.resource_script is not None:
            invocation.resource_script.unlink(missing_ok=True)
        if invocation.resource_output is not None:
            invocation.resource_output.unlink(missing_ok=True)
    if proc.returncode != 0:
        detail = (proc.stderr or proc.stdout).strip()
        raise ToolchainError(
            f"failed to compile the launcher with {compiler}",
            hint=detail[-2000:] or "the compiler exited without a message",
        )
    if not output.exists():
        raise ToolchainError(
            f"{compiler} reported success but did not produce {output}",
            hint="check the compiler output; antivirus software may have removed it",
        )
    make_executable(output)


def write_script_launcher(
    config: LauncherConfig,
    root: Path,
    *,
    target: Target,
) -> Path:
    """Write a shell/batch launcher as a fallback when no compiler is available.

    Script launchers only support ``onedir`` bundles: onefile requires the
    native launcher to extract the appended payload.
    """
    if config.onefile:
        raise ToolchainError(
            "onefile bundles require a native launcher (the launcher extracts the payload)",
            hint="install a C toolchain or build with --mode onedir --launcher script",
        )
    if target.is_windows:  # pragma: no cover - not exercised on this host
        content = (
            "@echo off\r\n"
            "setlocal\r\n"
            f'set "PYTHONHOME=%~dp0{config.home_rel}"\r\n'
            f'set "PYTHONPATH=%~dp0{config.site_rel}"\r\n'
            "set PYTHONNOUSERSITE=1\r\n"
            "set PYTHONSAFEPATH=1\r\n"
            "set PYTHONDONTWRITEBYTECODE=1\r\n"
            f'set "PYBUNDLER_ROOT=%~dp0"\r\n'
            f'"%~dp0{config.exe_rel}" -B -s -m _pybundler_boot %*\r\n'
        )
        path = root / f"{config.name}.cmd"
        write_text(path, content, mode=0o755)
        return path
    content = (
        "#!/bin/sh\n"
        'set -eu\n'
        'DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)\n'
        f'export PYTHONHOME="$DIR/{config.home_rel}"\n'
        f'export PYTHONPATH="$DIR/{config.site_rel}"\n'
        "export PYTHONNOUSERSITE=1\n"
        "export PYTHONSAFEPATH=1\n"
        "export PYTHONDONTWRITEBYTECODE=1\n"
        'export PYBUNDLER_ROOT="$DIR"\n'
        f'export PYBUNDLER_APP_PATH="$0"\n'
        f'export DYLD_LIBRARY_PATH="$DIR/{config.lib_rel}${{DYLD_LIBRARY_PATH:+:$DYLD_LIBRARY_PATH}}"\n'
        f'export LD_LIBRARY_PATH="$DIR/{config.lib_rel}${{LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}}"\n'
        f'case "${{1-}}" in\n'
        f'  -c|-m|-B|-s|-P) exec "$DIR/{config.exe_rel}" "$@" ;;\n'
        f'esac\n'
        f'exec "$DIR/{config.exe_rel}" -B -s -m _pybundler_boot "$@"\n'
    )
    path = root / config.name
    write_text(path, content, mode=0o755)
    return path


