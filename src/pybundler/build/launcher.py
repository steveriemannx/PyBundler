_COMPILE_HELPER = r"""
import importlib.util
import json
import os
import py_compile
import sys

strip = sys.argv[1] == "strip"
files = json.load(sys.stdin)
failures = []
for source in files:
    try:
        if strip:
            target = os.path.splitext(source)[0] + ".pyc"
        else:
            target = importlib.util.cache_from_source(source)
        py_compile.compile(
            source,
            cfile=target,
            doraise=True,
            optimize=0,
            invalidation_mode=py_compile.PycInvalidationMode.UNCHECKED_HASH,
        )
        if strip:
            os.unlink(source)
    except Exception as exc:  # noqa: BLE001 - report every failure to the caller
        failures.append([source, f"{type(exc).__name__}: {exc}"])
print(json.dumps(failures))
"""


def precompile(
    python: Path,
    *,
    home: Path,
    site_dir: Path,
    stdlib_dir: Path | None,
    strip_sources: bool,
    protect: set[Path] = frozenset(),
    logger: Logger | None = None,
    timeout: float = 900.0,
) -> list[str]:
    """Compile ``.py`` files in the bundle ahead of time.

    ``protect`` lists absolute paths whose source must survive even when
    ``strip_sources`` is set (the entry script is executed with ``runpy`` and
    therefore needs its file on disk).

    Returns a list of human readable failures (source path + message).  Build
    proceeds even if individual files fail, because a data file with a ``.py``
    suffix should not break the whole application.
    """
    failures: list[str] = []
    protected = {path.resolve() for path in protect}
    site_files = sorted(str(path) for path in site_dir.rglob("*.py")) if site_dir.is_dir() else []
    stripped = [path for path in site_files if strip_sources and Path(path).resolve() not in protected]
    kept = [path for path in site_files if strip_sources and Path(path).resolve() in protected]
    stdlib_files: list[str] = []
    if stdlib_dir is not None and stdlib_dir.is_dir():
        stdlib_files = sorted(str(path) for path in stdlib_dir.rglob("*.py"))
    env = sanitized_env(
        {
            "PYTHONHOME": str(home),
            "PYTHONNOUSERSITE": "1",
            "PYTHONDONTWRITEBYTECODE": "1",
            "PYTHONUTF8": "1",
        }
    )
    jobs: list[tuple[list[str], bool]] = []
    if stripped:
        jobs.append((stripped, True))
    if kept:
        jobs.append((kept, False))
    if stdlib_files:
        jobs.append((stdlib_files, False))
    for files, strip in jobs:
        if not files:
            continue
        proc = subprocess.run(
            [str(python), "-B", "-s", "-P", "-c", _COMPILE_HELPER, "strip" if strip else "keep"],
            input=json.dumps(files),
            capture_output=True,
            text=True,
            env=env,
            timeout=timeout,
        )
        if proc.returncode != 0:
            raise ToolchainError(
                "bytecode precompilation failed",
                hint=(proc.stderr or proc.stdout)[-2000:],
            )
        try:
            payload = json.loads(proc.stdout.strip().splitlines()[-1] or "[]")
        except (ValueError, IndexError):
            payload = []
        for source, message in payload:
            failures.append(f"{source}: {message}")
    if logger is not None and failures:
        for failure in failures[:20]:
            logger.detail(f"bytecode: {failure}")
        if len(failures) > 20:
            logger.detail(f"bytecode: ... and {len(failures) - 20} more")
    return failures
